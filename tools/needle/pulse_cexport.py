r"""Export a Pulse checkpoint for the firmware's C++ implementation (pulse_beat.cpp):

  pulse_weights.h        BatchNorm folded into the convs, float32, in the order pulse_beat.cpp runs them
  fixture_mel.f32        reference log-mel (128 x T, row = mel band) of a synthetic 20-s test signal
  fixture_logits.f32     reference beat / downbeat logits (2 x T) from pulse.predict_track on that mel
The C++ test (test_pulse_beat.cpp) builds the same signal from the same formula and compares.

    .venv\Scripts\python.exe pulse_cexport.py --model p4_w24_l6 --out F:\needle\pulse_c
"""
import argparse
import math
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

SR = 22050                  # torch and pulse.py are imported in main(): pulse_phase.py takes test_signal from here


def test_signal(seconds=20.0):
    """Kick on every beat (louder on beat 1), hat on the off-beats, a bass note per bar; 128 BPM."""
    n = np.arange(int(seconds * SR), dtype=np.float64)
    t = n / SR
    beat = 60.0 / 128.0
    tb = np.fmod(t, beat)
    one = (np.floor(t / beat).astype(np.int64) % 4) == 0
    kick = np.sin(2 * math.pi * 55.0 * tb) * np.exp(-tb / 0.12) * np.where(one, 0.8, 0.55)
    off = np.fmod(t + beat / 2, beat)
    hat = 0.15 * np.sin(2 * math.pi * 8000.0 * off) * np.exp(-off / 0.015)
    bar = np.floor(t / (4 * beat)).astype(np.int64)
    bass = 0.25 * np.sin(2 * math.pi * 55.0 * np.power(2.0, (bar % 4) * 3 / 12.0) * t)
    return (kick + hat + bass).astype(np.float32)


def fold(seq):
    import torch
    conv, bn = seq[0], seq[1]
    s = bn.weight / torch.sqrt(bn.running_var + bn.eps)
    return (conv.weight * s[:, None, None, None]).detach(), (bn.bias - bn.running_mean * s).detach(), conv.stride, conv.padding, True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="p4_w24_l6")
    ap.add_argument("--out", default=r"F:\needle\pulse_c")
    a = ap.parse_args()
    import torch
    from pulse import Pulse, predict_track
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    run = HERE / "runs_pulse" / a.model
    ck = torch.load(run / ("best.pt" if (run / "best.pt").exists() else "last.pt"), map_location="cpu", weights_only=False)
    model = Pulse(ck["width"], ck.get("levels", 5))
    model.load_state_dict(ck["model"])
    model.eval()

    layers = [fold(s) for s in model.stem]
    for d, m in zip(model.down, model.mid):
        layers += [fold(d), fold(m)]
    layers += [fold(u) for u in model.up]
    layers.append((model.head.weight.detach(), model.head.bias.detach(), model.head.stride, model.head.padding, False))

    lines = ["#pragma once", f"// Pulse weights: {a.model} (step {ck.get('step')}), BatchNorm folded. Generated by pulse_cexport.py.",
             "namespace PulseWeights {", "struct Conv { int cout, cin, kh, kw, sh, sw, ph, pw; bool relu; const float* w; const float* b; };",
             f"constexpr int kWidth = {ck['width']};", f"constexpr int kLevels = {model.levels};", f"constexpr int kStem = {len(model.stem)};"]
    table = []
    total = 0
    for i, (w, b, st, pd, relu) in enumerate(layers):
        wf = w.numpy().astype(np.float32).ravel()
        bf = b.numpy().astype(np.float32).ravel()
        total += wf.size + bf.size
        lines.append(f"static const float w{i}[] = {{" + ",".join(f"{v:.9g}f" for v in wf) + "};")
        lines.append(f"static const float b{i}[] = {{" + ",".join(f"{v:.9g}f" for v in bf) + "};")
        co, ci, kh, kw = w.shape
        table.append(f"  {{{co}, {ci}, {kh}, {kw}, {st[0]}, {st[1]}, {pd[0]}, {pd[1]}, {'true' if relu else 'false'}, w{i}, b{i}}},")
    lines.append(f"// {total} parameters in {len(layers)} convolutions")
    lines.append("static const Conv kConvs[] = {")
    lines += table
    lines += ["};", "}  // namespace PulseWeights", ""]
    (out / "pulse_weights.h").write_text("\n".join(lines), encoding="ascii")

    from beat_this.preprocessing import LogMelSpect
    x = test_signal()
    mel = LogMelSpect(device="cpu")(torch.from_numpy(x)).T.numpy().astype(np.float32)      # (128, T)
    mel.tofile(out / "fixture_mel.f32")
    with torch.inference_mode():
        y = predict_track(model, mel, "cpu").numpy().astype(np.float32)                    # (2, T)
    y.tofile(out / "fixture_logits.f32")
    print(f"{a.model}: {total} parameters, {len(layers)} convs; fixture T={mel.shape[1]}, "
          f"mel range {mel.min():.3f}..{mel.max():.3f}, beat logit max {y[0].max():.2f}")


if __name__ == "__main__":
    main()
